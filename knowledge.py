def expand(count=40000, seed=7):
    """把领域问答扩展成多种问法变体，提高检索召回率。

    比如「足球一场比赛多少人」→ 也会写成「一场足球比赛有多少人上场」。
    """
    import random
    r = random.Random(seed)
    out = []
    domains = all_domains()
    prefixes = ["", "请问", "我想知道", "能不能说说", "你知道"]
    suffixes = ["", "呢", "啊", "？"]
    for _ in range(count):
        pool = r.choice(list(domains.values()))
        q, a = r.choice(pool)
        # 问法变体：加前缀后缀
        q2 = r.choice(prefixes) + q + r.choice(suffixes)
        out.append((q2, a))
    return out
