def cn_num(n: int) -> str:
    if n < 10:
        return CN[n]
    if n < 20:
        return "十" + (CN[n % 10] if n % 10 else "")
    if n < 100:
        t, o = divmod(n, 10)
        return CN[t] + "十" + (CN[o] if o else "")
    return str(n)


