def build_templates(count: int):
    """从 intents 里随机组合问答。"""
    out = []
    for _ in range(count):
        qs, as_ = random.choice(INTENTS)
        out.append((random.choice(qs), random.choice(as_)))
    return out


def build_math(count: int):
    """算术问答，答案保证正确。"""
    out = []
    ops = ["加", "减", "乘"]
    for _ in range(count):
        op = random.choice(ops)
        if op == "加":
            a, b = random.randint(1, 50), random.randint(1, 50)
            r = a + b
        elif op == "减":
            a, b = random.randint(1, 50), random.randint(1, 50)
            a, b = max(a, b), min(a, b)
            r = a - b
        else:
            a, b = random.randint(1, 9), random.randint(1, 9)
            r = a * b
        if op == "乘":
            q = f"{cn_num(a)}乘以{cn_num(b)}等于几"
        else:
            q = f"{cn_num(a)}{op}{cn_num(b)}等于几"
        out.append((q, f"{q[:-3]}等于{cn_num(r)}。"))
    return out


def build_compare(count: int):
    out = []
    for _ in range(count):
        a, b = random.randint(1, 99), random.randint(1, 99)
        if a > b:
            ans = f"{cn_num(a)}比{cn_num(b)}大。"
        elif a < b:
            ans = f"{cn_num(a)}比{cn_num(b)}小。"
        else:
            ans = f"{cn_num(a)}和{cn_num(b)}一样大。"
        out.append((f"{cn_num(a)}和{cn_num(b)}哪个大", ans))
    return out


def main():
    pairs = []
    pairs += build_templates(9000)
    pairs += build_math(3000)
    pairs += build_compare(1000)
    random.shuffle(pairs)

    here = os.path.dirname(os.path.abspath(__file__))
    outdir = os.path.join(here, "data")
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, "corpus.txt")

    with open(path, "w", encoding="utf-8") as f:
        for q, a in pairs:
            f.write(f"问：{q}\n答：{a}\n")

    size = os.path.getsize(path)
    chars = set(open(path, encoding="utf-8").read())
    print(f"条数: {len(pairs)}")
    print(f"字节: {size / 1024:.1f} KB")
    print(f"不同字符: {len(chars)}")
    print(f"路径: {path}")


if __name__ == "__main__":
    main()
