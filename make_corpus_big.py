def gen_math(count):
    out = []
    for _ in range(count):
        op = random.choice(["加", "减", "乘"])
        if op == "加":
            a, b = random.randint(1, 99), random.randint(1, 99)
            r = a + b
            q = f"{cn_num(a)}加{cn_num(b)}等于几"
        elif op == "减":
            a, b = random.randint(1, 99), random.randint(1, 99)
            a, b = max(a, b), min(a, b)
            r = a - b
            q = f"{cn_num(a)}减{cn_num(b)}等于几"
        else:
            a, b = random.randint(1, 19), random.randint(1, 19)
            r = a * b
            q = f"{cn_num(a)}乘以{cn_num(b)}等于几"
        out.append((q, f"{q[:-3]}等于{cn_num(r)}。"))
    return out


def gen_compare(count):
    out = []
    for _ in range(count):
        a, b = random.randint(1, 99), random.randint(1, 99)
        if a > b:
            ans = f"{cn_num(a)}比{cn_num(b)}大。"
        elif a < b:
            ans = f"{cn_num(a)}比{cn_num(b)}小。"
        else:
            ans = f"{cn_num(a)}和{cn_num(b)}一样大。"
        out.append((f"{cn_num(a)}和{cn_num(b)}哪个大", ans))
    return out


