def gen_slots(count):
    out = []
    for _ in range(count):
        k = random.randint(0, 9)
        p, t, pl, o = random.choice(PERSON), random.choice(TIME), random.choice(PLACE), random.choice(OBJ)
        v, a, f, e = random.choice(VERB), random.choice(ADJ), random.choice(FOOD), random.choice(EMO)

        if k == 0:
            q = f"{t}你打算做什么"
            ans = f"{t}我{random.choice(VERB)}去{pl}，顺便把{o}{random.choice(VERB)}好。"
        elif k == 1:
            q = f"为什么{p}{t}看起来有点{e}"
            ans = f"因为{t}的事情不太{a}，不过现在好多了。"
        elif k == 2:
            q = f"{p}在{pl}做什么"
            ans = f"{p}在{pl}{random.choice(VERB)}{o}，看起来挺{a}的。"
        elif k == 3:
            q = f"{t}吃什么比较好"
            ans = f"要不试试{f}？{t}吃这个挺合适的。"
        elif k == 4:
            q = f"怎么才能把{o}{random.choice(VERB)}好"
            ans = f"先列个清单，再一件一件来，别一次做太多。"
        elif k == 5:
            q = f"{p}觉得{random.choice(TOPICS)}重要吗"
            ans = f"挺重要的，坚持下来会有明显变化。"
        elif k == 6:
            q = f"最近{random.choice(TOPICS)}怎么样"
            ans = f"还行，每天花一点时间，慢慢就有感觉了。"
        elif k == 7:
            q = f"{t}的天气适合去{pl}吗"
            ans = f"适合，不过记得看看天气，带把伞更稳妥。"
        elif k == 8:
            q = f"{p}{t}心情怎么样"
            ans = f"{t}心情还算{a}，就是有点{e}。"
        else:
            q = f"{o}放在哪里了"
            ans = f"应该在{pl}那边，你找找看。"

        out.append((q, ans))
    return out


